"""Concrete selection signals and neighboring-pattern distinctions."""

DECISIONS = {}


def add(slug, signal, scenarios, comparisons):
    DECISIONS[slug] = {
        "signal": signal,
        "scenarios": scenarios.split("|"),
        "comparisons": [part.split("^") for part in comparisons.split("|")],
    }


add("layered-architecture",
    "应用职责能按表示、业务、数据访问划清，且主要是进程内调用。",
    "常规企业应用把 HTTP、用例和数据库职责分开|团队需要清楚的模块边界与单向依赖规则|从混杂的控制器中抽出稳定业务逻辑",
    "整洁架构^都强调边界；整洁架构进一步要求依赖方向指向业务核心，数据库只是外层细节。|微服务^跨进程拆分部署；分层架构可完全在一个进程内实现。")
add("soa",
    "多个业务流程需要复用有明确契约的企业服务。",
    "订单与售后流程共用客户服务|跨系统复用库存或身份能力|大型组织治理长期稳定的服务契约",
    "微服务^微服务更强调独立部署与自治数据边界；SOA 更强调企业级服务复用与集成治理。|模块化单体^进程内模块协作成本低；SOA 的跨服务调用带来网络失败与契约治理。")
add("event-driven-architecture",
    "事实发生后多个下游可独立响应，业务允许异步与最终一致。",
    "订单支付后积分与通知各自消费|库存变化触发搜索索引更新|设备遥测驱动多个实时分析服务",
    "观察者模式^观察者通常是进程内回调；跨服务事件需要持久化、重试和幂等。|同步 RPC^RPC 调用方等待结果；事件驱动的下游可异步处理，但要接受延迟与乱序。")
add("monolith-vs-microservices",
    "不同业务能力有独立交付、扩缩容或团队自治的真实需求。",
    "订单与搜索负载特征差异明显|多个团队需要独立发布且边界清楚|某能力故障需要与其他能力隔离",
    "模块化单体^可先在单进程内建立清晰业务边界，部署简单。|SOA^两者都服务化；微服务通常划更细的自治边界并强调独立交付。")
add("mvc-pattern",
    "交互系统需要把输入处理、业务数据与呈现职责分开。",
    "Web 控制器查订单后渲染页面|桌面应用的数据变化驱动视图更新|同一模型支持不同界面展示",
    "MVP^Presenter 更完整地协调视图，View 通常更被动。|MVVM^ViewModel 借助数据绑定同步 View，常见于前端与移动端。")
add("pipe-filter-pattern",
    "数据可被拆成输入输出契约清楚的顺序处理阶段。",
    "日志解析、校验、脱敏、写出流水线|编译器词法、语法、优化阶段|媒体文件转码的多段处理",
    "责任链^责任链的某环可终止或处理请求；管道过滤器重在每段转换数据并交给下一段。|工作流编排^工作流可能有分支、等待和回退；线性管道更适合连续转换。")
add("clean-architecture",
    "业务规则要长期独立于 Web 框架、数据库和外部服务。",
    "核心定价规则要在不同接口复用|更换数据库时不改业务用例|单元测试不启动外部基础设施",
    "六边形架构^两者都让核心隔离外部；六边形以端口和适配器描述边界，整洁架构更强调同心层级和依赖规则。|传统分层^分层可能让业务层依赖具体数据层；整洁架构要求依赖箭头指向内部。")
add("hexagonal-architecture",
    "同一业务能力要接受多个输入入口，并能替换外部输出技术。",
    "HTTP 与 CLI 共用下单用例|仓储实现从 MySQL 切到内存测试|外部支付供应商由适配器隔离",
    "整洁架构^都保护业务核心；六边形用输入/输出端口明确交互点，整洁架构强调层级依赖。|GoF 适配器^端口适配器可使用 Adapter 模式；六边形描述整个应用边界。")
add("cqrs-pattern",
    "写入规则与读取视图的模型需求差异明显，值得分别设计。",
    "写订单重规则、查订单列表重聚合|读流量远高于写流量且要独立扩展|需要多个专用查询投影",
    "数据库读写分离^读写分离可只是主从副本路由；CQRS 把命令模型与查询模型的职责分开。|事件溯源^事件溯源用事件记录事实历史；CQRS 不要求以事件作为权威存储。")
add("api-gateway",
    "多个后端服务需要统一外部入口、路由和公共入口治理。",
    "移动端统一访问订单与用户服务|统一入口鉴权和限流|按路径或版本把请求转发给不同服务",
    "反向代理^网关常基于反向代理，但还承载 API 级鉴权、路由和治理语义。|BFF^BFF 按具体前端需求聚合接口；通用网关通常是跨客户端的公共入口。")
add("service-discovery",
    "服务实例地址频繁变化，调用方不能维护静态 IP 列表。",
    "容器实例弹性扩缩容|故障实例从可用列表摘除|多个实例间按健康状态做路由",
    "负载均衡^发现负责取得可用实例列表；负载均衡在列表中选目标，二者常配合。|API 网关^网关是外部入口；服务发现帮助内部调用方定位服务实例。")
add("circuit-breaker",
    "下游持续失败或超时，继续调用会耗尽上游资源。",
    "支付供应商异常时快速失败|推荐服务故障时回退空结果|半开探测恢复后的下游",
    "重试^重试尝试克服瞬时失败；熔断在持续失败时停止继续施压。|限流^限流按流量控制进入量；熔断根据下游健康状态暂停调用。")
add("rate-limit-degrade",
    "流量超过容量或非核心能力过载，必须保护关键业务。",
    "秒杀入口按令牌桶限制请求|推荐模块过载时只保留下单|高峰期对低优先级接口返回简化结果",
    "限流^决定哪些请求可进入，超额请求会被拒绝或排队。|降级^接受请求但减少可选功能；二者可同时使用。")
add("idempotency-design",
    "客户端可能因超时或消息重投重复执行同一业务操作。",
    "付款请求带幂等键避免重复扣款|消息消费重复投递时只记一次积分|创建订单接口因网络超时重试",
    "重试^重试提高瞬时失败后的成功率；幂等保证重复尝试不会重复产生副作用。|去重^去重是常见实现手段；完整幂等还包括相同结果返回与处理中状态恢复。")
add("saga-pattern",
    "跨服务业务步骤都能独立提交，并可定义反向补偿。",
    "机票、酒店、租车串行预约|订单、库存、支付的最终一致流程|支付失败后释放已预留资源",
    "两阶段提交^2PC 通过协调锁定参与者追求原子提交；Saga 通过本地事务和业务补偿达到最终一致。|Outbox^Outbox 保证本地状态和待发事件一起提交；Saga 管跨步骤的正向与补偿流程。")
